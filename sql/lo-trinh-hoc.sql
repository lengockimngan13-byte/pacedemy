-- ĐÃ CHẠY trên Supabase ngày 07/10/2026. Giữ lại làm bản ghi,
-- KHÔNG cần chạy lại.
--
-- Ba phần:
--   1. lo_trinh / lo_trinh_tuan / lo_trinh_viec — mẫu cô soạn một lần.
--   2. hoc_vien_lo_trinh — em nào đang theo mẫu nào, từ ngày nào.
--      Tuần 1 tính từ ngày gắn, nên mỗi em một khung ngày riêng dù
--      dùng chung một mẫu.
--   3. viec_rieng — việc cô lồng thêm cho riêng một em, nhắm đúng chỗ
--      em đó hay sai. Nằm ngoài mẫu nên sửa mẫu không làm mất.
--
-- Tiến độ KHÔNG lưu ở đâu cả. lo_trinh_tien_do() đếm lại từ dữ liệu
-- thật trong đúng khung ngày của tuần, nên không có chuyện đánh dấu
-- đã xong cho có. Để trong Postgres vì mỗi tuần phải hỏi vài bảng
-- khác nhau; gọi từ trình duyệt thì tám tuần là hai mươi mấy chuyến.
--
-- lt_deu() đếm số NGÀY có học chứ không đếm số bài: hai em cùng làm
-- 100 câu một tuần, một em rải năm buổi, một em làm dồn một tối, kết
-- quả thi khác hẳn nhau.
--
-- Cả ba hàm đều security definer nên tự kiểm quyền: chỉ giáo viên,
-- hoặc chính em đó, mới xem được.
-- ============================================================

create table if not exists public.lo_trinh (
  id          bigint generated by default as identity primary key,
  ten         text not null,
  mo_ta       text,
  muc_tieu    integer,
  ky_nang     text not null default 'all' check (ky_nang in ('all','listening','reading')),
  so_tuan     integer not null default 4 check (so_tuan between 1 and 52),
  is_active   boolean not null default true,
  created_at  timestamptz not null default now()
);

create table if not exists public.lo_trinh_tuan (
  id          bigint generated by default as identity primary key,
  lo_trinh_id bigint not null references public.lo_trinh(id) on delete cascade,
  tuan        integer not null check (tuan >= 1),
  tieu_de     text not null,
  ghi_chu     text,
  unique (lo_trinh_id, tuan)
);

create table if not exists public.lo_trinh_viec (
  id          bigint generated by default as identity primary key,
  tuan_id     bigint not null references public.lo_trinh_tuan(id) on delete cascade,
  kind        text not null check (kind in ('vocab','part5','listen','read','mock')),
  target      text,
  label       text not null,
  amount      integer not null default 10 check (amount >= 1),
  order_index integer not null default 0
);

-- Một em có thể theo vài lộ trình cùng lúc, ví dụ 650+ chạy nền và
-- một lộ trình chữa Listening ngắn hạn.
create table if not exists public.hoc_vien_lo_trinh (
  id            bigint generated by default as identity primary key,
  student_id    uuid not null references public.profiles(id) on delete cascade,
  lo_trinh_id   bigint not null references public.lo_trinh(id) on delete cascade,
  bat_dau       date not null default current_date,
  buoi_moi_tuan integer not null default 5 check (buoi_moi_tuan between 1 and 7),
  ghi_chu       text,
  is_active     boolean not null default true,
  created_by    uuid,
  created_at    timestamptz not null default now()
);

create index if not exists hv_lo_trinh_sv_idx on public.hoc_vien_lo_trinh (student_id) where is_active;

create table if not exists public.viec_rieng (
  id          bigint generated by default as identity primary key,
  hv_lt_id    bigint not null references public.hoc_vien_lo_trinh(id) on delete cascade,
  tuan        integer not null check (tuan >= 1),
  kind        text not null check (kind in ('vocab','part5','listen','read','mock')),
  target      text,
  label       text not null,
  amount      integer not null default 10 check (amount >= 1),
  ly_do       text,
  created_at  timestamptz not null default now()
);

create index if not exists viec_rieng_hv_idx on public.viec_rieng (hv_lt_id, tuan);

-- Đếm nhanh hơn khi dò theo khung ngày
create index if not exists attempts_user_time_idx on public.attempts (user_id, started_at);
create index if not exists vocab_progress_user_time_idx on public.vocab_progress (user_id, last_reviewed);
create index if not exists mock_tests_user_time_idx on public.mock_tests (user_id, submitted_at);

alter table public.lo_trinh          enable row level security;
alter table public.lo_trinh_tuan     enable row level security;
alter table public.lo_trinh_viec     enable row level security;
alter table public.hoc_vien_lo_trinh enable row level security;
alter table public.viec_rieng        enable row level security;

-- Mẫu lộ trình cho người đã đăng nhập đọc: học viên phải thấy được
-- tuần này mình cần làm gì. Chỉ cô mới sửa.
create policy lo_trinh_doc      on public.lo_trinh      for select using (auth.uid() is not null);
create policy lo_trinh_co       on public.lo_trinh      for all using (is_teacher()) with check (is_teacher());
create policy lo_trinh_tuan_doc on public.lo_trinh_tuan for select using (auth.uid() is not null);
create policy lo_trinh_tuan_co  on public.lo_trinh_tuan for all using (is_teacher()) with check (is_teacher());
create policy lo_trinh_viec_doc on public.lo_trinh_viec for select using (auth.uid() is not null);
create policy lo_trinh_viec_co  on public.lo_trinh_viec for all using (is_teacher()) with check (is_teacher());

create policy hv_lt_doc on public.hoc_vien_lo_trinh for select
  using (auth.uid() = student_id or is_teacher());
create policy hv_lt_co  on public.hoc_vien_lo_trinh for all
  using (is_teacher()) with check (is_teacher());

create policy viec_rieng_doc on public.viec_rieng for select
  using (is_teacher() or exists (
    select 1 from public.hoc_vien_lo_trinh h
    where h.id = viec_rieng.hv_lt_id and h.student_id = auth.uid()));
create policy viec_rieng_co on public.viec_rieng for all
  using (is_teacher()) with check (is_teacher());


